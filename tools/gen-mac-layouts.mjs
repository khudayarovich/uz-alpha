// Builds the two macOS keyboard layouts from the kiritish.uz layout:
//
//   Özbekça (lotin, qölda)      - the kiritish.uz layout, renamed.
//   Özbekça (lotin, avtomatik)  - US QWERTY where sh, ch, o', g' become ş, ç, ö, ğ.
//
//   node tools/gen-mac-layouts.mjs third_party/kiritish/ozbekcha-yangi-alifbo.keylayout mac/UzAlpha.bundle/Contents/Resources
//
// Auto works with the layout's dead-key state machine: s, c, o, g (both
// cases) each enter a state whose terminator is the letter itself. macOS, when
// a key has no entry for the current state, outputs the terminator and then
// handles the key from the start, so "tog'" gives t, o-pending, o + g-pending,
// ğ. The script simulates that rule on the generated tables before writing.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [, , inputPath, outDir] = process.argv;
if (!inputPath || !outDir) {
  console.error('usage: node tools/gen-mac-layouts.mjs <kiritish.keylayout> <output dir>');
  process.exit(2);
}

// `name` is what macOS shows in its keyboard list.
const MANUAL = { name: 'Özbekça (lotin, qölda)', id: -24871, file: 'UzAlphaManual.keylayout' };
const AUTO = { name: 'Özbekça (lotin, avtomatik)', id: -24872, file: 'UzAlphaAuto.keylayout' };

const source = readFileSync(inputPath, 'utf8');

function retitle(xml, layout) {
  const re = /<keyboard group="(-?\d+)" id="-?\d+" name="[^"]*"/;
  if (!re.test(xml)) throw new Error('<keyboard> element not found');
  const credit =
    '<!--UzAlpha: generated by tools/gen-mac-layouts.mjs from the kiritish.uz layout ' +
    '(MIT licence, (c) 2026 Bilolbek Normuminov).-->\n';
  return xml
    .replace(re, (_, group) => `<keyboard group="${group}" id="${layout.id}" name="${layout.name}"`)
    .replace(/(<keyboard )/, credit + '$1');
}

// In the original, Shift or Option together with Caps Lock matches no entry
// and falls through to the (empty) Control map. Accept Caps Lock there.
function fixModifiers(xml) {
  const a = '<modifier keys="anyShift"/>';
  const b = '<modifier keys="anyOption"/>';
  if (!xml.includes(a) || !xml.includes(b)) throw new Error('unexpected modifier map');
  return xml.replace(a, '<modifier keys="anyShift caps?"/>').replace(b, '<modifier keys="anyOption caps?"/>');
}

// --- Auto -----------------------------------------------------------------
const out = (s) => ({ output: s });
const act = (s) => ({ action: s });
const QUOTE = '&#x0022;';

// Key codes: 1 s, 4 h, 5 g, 8 c, 31 o, 39 ', 41 ;, 33 [, 30 ], 42 \, 50 `
const AUTO_KEYS = {
  0: { 1: act('s'), 8: act('c'), 31: act('o'), 5: act('g'), 4: act('h'), 39: act('apos'),
       41: out(';'), 33: out('['), 30: out(']'), 42: out('\\'), 50: act('grave') },
  1: { 1: act('S'), 8: act('C'), 31: act('O'), 5: act('G'), 4: act('H'), 39: out(QUOTE),
       41: out(':'), 33: out('{'), 30: out('}'), 42: out('|'), 50: out('~') },
  5: { 1: act('S'), 8: act('C'), 31: act('O'), 5: act('G'), 4: act('H'), 39: act('apos'),
       41: out(';'), 33: out('['), 30: out(']'), 42: out('\\'), 50: act('grave') },
};

const STARTERS = { s: 'ş', S: 'Ş', c: 'ç', C: 'Ç', o: 'ö', O: 'Ö', g: 'ğ', G: 'Ğ' };

function actionsXml() {
  const lines = ['    <actions>'];
  for (const letter of Object.keys(STARTERS)) {
    lines.push(`        <action id="${letter}">`, `            <when state="none" next="${letter}"/>`, '        </action>');
  }
  for (const h of ['h', 'H']) {
    lines.push(`        <action id="${h}">`, `            <when state="none" output="${h}"/>`);
    for (const s of ['s', 'S', 'c', 'C']) lines.push(`            <when state="${s}" output="${STARTERS[s]}"/>`);
    lines.push('        </action>');
  }
  // o' and o` both give ö. On its own the apostrophe types ʼ, the backtick stays `.
  for (const [id, alone] of [['apos', 'ʼ'], ['grave', '`']]) {
    lines.push(`        <action id="${id}">`, `            <when state="none" output="${alone}"/>`);
    for (const s of ['o', 'O', 'g', 'G']) lines.push(`            <when state="${s}" output="${STARTERS[s]}"/>`);
    lines.push('        </action>');
  }
  lines.push('    </actions>', '    <terminators>');
  for (const letter of Object.keys(STARTERS)) lines.push(`        <when state="${letter}" output="${letter}"/>`);
  lines.push('    </terminators>');
  return lines.join('\n') + '\n';
}

function makeAuto(xml) {
  const lines = xml.split('\n');
  let set = null;
  let map = null;
  let replaced = 0;
  const result = lines.map((line) => {
    let m;
    if ((m = line.match(/<keyMapSet id="([^"]+)"/))) set = m[1];
    if ((m = line.match(/<keyMap index="(\d+)"/))) map = Number(m[1]);
    if (set !== 'ANSI' || !(map in AUTO_KEYS)) return line;
    m = line.match(/^(\s*)<key code="(\d+)" output="[^"]*"\/>(\r?)$/);
    if (!m) return line;
    const spec = AUTO_KEYS[map][Number(m[2])];
    if (!spec) return line;
    replaced++;
    const attr = spec.action ? `action="${spec.action}"` : `output="${spec.output}"`;
    return `${m[1]}<key code="${m[2]}" ${attr}/>${m[3]}`;
  });
  const expected = Object.values(AUTO_KEYS).reduce((n, keys) => n + Object.keys(keys).length, 0);
  if (replaced !== expected) throw new Error(`replaced ${replaced} keys, expected ${expected}`);

  const joined = result.join('\n');
  const close = joined.lastIndexOf('</keyboard>');
  if (close < 0) throw new Error('</keyboard> not found');
  return joined.slice(0, close) + actionsXml() + joined.slice(close);
}

// --- checks ---------------------------------------------------------------
function assertWellFormed(xml, label) {
  const stack = [];
  const re = /<(\/?)([A-Za-z][\w.-]*)((?:\s+[\w:.-]+="[^"<]*")*)\s*(\/?)>|<\?[\s\S]*?\?>|<!--[\s\S]*?-->|<!DOCTYPE[^>]*>/g;
  let m;
  let last = 0;
  while ((m = re.exec(xml))) {
    const between = xml.slice(last, m.index);
    if (/[<>]/.test(between)) throw new Error(`${label}: stray markup near offset ${last}`);
    last = re.lastIndex;
    if (!m[2]) continue;
    if (m[1]) {
      const open = stack.pop();
      if (open !== m[2]) throw new Error(`${label}: </${m[2]}> closes <${open}>`);
    } else if (!m[4]) {
      stack.push(m[2]);
    }
  }
  if (/[<>]/.test(xml.slice(last))) throw new Error(`${label}: stray markup at the end`);
  if (stack.length) throw new Error(`${label}: unclosed <${stack.pop()}>`);
}

const unescape = (s) => s.replace(/&#x([0-9A-Fa-f]+);/g, (_, h) => String.fromCodePoint(parseInt(h, 16)));

// Runs the layout's state machine the way macOS does (UCKeyTranslate).
function simulator(xml) {
  const maps = {};
  let set = null;
  let map = null;
  for (const line of xml.split('\n')) {
    let m;
    if ((m = line.match(/<keyMapSet id="([^"]+)"/))) set = m[1];
    if ((m = line.match(/<keyMap index="(\d+)"/))) map = Number(m[1]);
    if (set !== 'ANSI') continue;
    if ((m = line.match(/<key code="(\d+)" (output|action)="([^"]*)"\/>/))) {
      (maps[map] ??= {})[Number(m[1])] = { [m[2]]: unescape(m[3]) };
    }
  }
  const actions = {};
  for (const m of xml.matchAll(/<action id="([^"]+)">([\s\S]*?)<\/action>/g)) {
    const whens = {};
    for (const w of m[2].matchAll(/<when state="([^"]+)"(?: output="([^"]*)")?(?: next="([^"]*)")?\/>/g)) {
      whens[w[1]] = { output: w[2] === undefined ? undefined : unescape(w[2]), next: w[3] };
    }
    actions[m[1]] = whens;
  }
  const terminators = {};
  const block = xml.match(/<terminators>([\s\S]*?)<\/terminators>/);
  if (block) {
    for (const w of block[1].matchAll(/<when state="([^"]+)" output="([^"]*)"\/>/g)) terminators[w[1]] = unescape(w[2]);
  }

  // US positions of the characters used in the tests.
  const codes = { a: 0, s: 1, d: 2, f: 3, h: 4, g: 5, z: 6, x: 7, c: 8, v: 9, b: 11, q: 12, w: 13, e: 14, r: 15,
                  y: 16, t: 17, o: 31, u: 32, i: 34, p: 35, l: 37, j: 38, k: 40, n: 45, m: 46,
                  "'": 39, ';': 41, '[': 33, ']': 30, ' ': 49, '`': 50 };
  return (text) => {
    let state = 'none';
    let result = '';
    for (const ch of text) {
      const upper = ch !== ch.toLowerCase();
      const code = codes[ch.toLowerCase()];
      if (code === undefined) throw new Error(`no key for "${ch}" in the simulator`);
      const key = maps[upper ? 1 : 0][code];
      if (key.output !== undefined) {
        if (state !== 'none') result += terminators[state] ?? '';
        state = 'none';
        result += key.output;
        continue;
      }
      const whens = actions[key.action];
      let w = whens[state];
      if (!w) {
        result += terminators[state] ?? '';
        w = whens.none ?? {};
      }
      if (w.output !== undefined) result += w.output;
      state = w.next ?? 'none';
    }
    if (state !== 'none') result += terminators[state] ?? '';  // shown as pending text
    return result;
  };
}

function check(type, input, want) {
  const got = type(input);
  if (got !== want) throw new Error(`auto layout: "${input}" gives "${got}", expected "${want}"`);
}

// --- build ----------------------------------------------------------------
const manual = fixModifiers(retitle(source, MANUAL));
const auto = makeAuto(fixModifiers(retitle(source, AUTO)));

assertWellFormed(manual, MANUAL.file);
assertWellFormed(auto, AUTO.file);

const type = simulator(auto);
check(type, 'shahar', 'şahar');
check(type, 'choy', 'çoy');
check(type, "o'zbek", 'özbek');
check(type, "g'isht", 'ğişt');
check(type, "tog'", 'toğ');
check(type, "to'g'ri", 'töğri');
check(type, 'mashhur', 'maşhur');
check(type, 'Shahar', 'Şahar');
check(type, 'SHAHAR', 'ŞAHAR');
check(type, "O'zbek", 'Özbek');
check(type, 'ss', 'ss');
check(type, 'sa', 'sa');
check(type, "ma'no", 'maʼno');
check(type, "is'hoq", 'isʼhoq');
check(type, 'salom; [dunyo]', 'salom; [dunyo]');
check(type, "Yangi o'zbek alifbosi uchun", 'Yangi özbek alifbosi uçun');
check(type, 'o`zbek to`g`ri', 'özbek töğri');
check(type, 'a`b', 'a`b');

// The manual layout must still type the kiritish.uz letters.
const typeManual = simulator(manual);
check(typeManual, ";'[]", 'şçöğ');

// --- Info.plist -------------------------------------------------------------
// Each layout gets a KLInfo_<key> entry carrying its input source id and
// language. Which <key> macOS matches is not documented for XML layouts, so
// EXPERIMENT writes every plausible form with a distinguishable id; the macOS
// test prints the id macOS ends up using.
const BUNDLE_ID = 'uz.uzalpha.keyboardlayout.uzalpha';
const EXPERIMENT = true;

function klInfoKeys(layout, short) {
  const file = layout.file.replace(/\.keylayout$/, '');
  if (!EXPERIMENT) return [[file, `${BUNDLE_ID}.${short}`]];
  return [
    [file, `${BUNDLE_ID}.${short}.byfile`],
    [layout.name.normalize('NFC'), `${BUNDLE_ID}.${short}.byname`],
    [layout.name.normalize('NFD'), `${BUNDLE_ID}.${short}.bynamenfd`],
    [layout.name.replace(/[^\p{L}\p{N}]/gu, ''), `${BUNDLE_ID}.${short}.bysanitized`],
    [String(layout.id), `${BUNDLE_ID}.${short}.bynumber`],
  ];
}

function infoPlist() {
  const entries = [];
  for (const [layout, short] of [[AUTO, 'auto'], [MANUAL, 'manual']]) {
    const seen = new Set();
    for (const [key, id] of klInfoKeys(layout, short)) {
      if (seen.has(key)) continue;
      seen.add(key);
      entries.push(
        `\t<key>KLInfo_${key}</key>`,
        '\t<dict>',
        '\t\t<key>TISInputSourceID</key>',
        `\t\t<string>${id}</string>`,
        '\t\t<key>TISIntendedLanguage</key>',
        '\t\t<string>uz</string>',
        '\t</dict>',
      );
    }
  }
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<!-- Generated by tools/gen-mac-layouts.mjs -->',
    '<plist version="1.0">',
    '<dict>',
    '\t<key>CFBundleIdentifier</key>',
    `\t<string>${BUNDLE_ID}</string>`,
    '\t<key>CFBundleName</key>',
    '\t<string>UzAlpha</string>',
    '\t<key>CFBundleVersion</key>',
    '\t<string>1.0.0</string>',
    '\t<key>CFBundleShortVersionString</key>',
    '\t<string>1.0.0</string>',
    ...entries,
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, MANUAL.file), manual, 'utf8');
writeFileSync(join(outDir, AUTO.file), auto, 'utf8');
writeFileSync(join(outDir, '..', 'Info.plist'), infoPlist(), 'utf8');
console.log(`wrote ${MANUAL.file} and ${AUTO.file} to ${outDir} (typing checks passed)`);
