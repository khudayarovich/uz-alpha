// Turns an MSKLC .klc keyboard description into the C source of a Windows
// keyboard layout DLL (the same shape kbdutool produces).
//
//   node tools/klc2c.mjs third_party/kiritish/new-uzb.klc src/kbd/kbduzalp.c
//
// Supports what the Manual layout needs: plain characters, CapsLock flag,
// AltGr. Dead keys, ligatures and SGCaps are rejected rather than ignored.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , klcPath, outPath] = process.argv;
if (!klcPath || !outPath) {
  console.error('usage: node tools/klc2c.mjs <in.klc> <out.c>');
  process.exit(2);
}

const lines = readFileSync(klcPath, 'utf8').replace(/^﻿/, '').split(/\r?\n/);
const SECTIONS = ['SHIFTSTATE', 'LAYOUT', 'DEADKEY', 'LIGATURE', 'KEYNAME', 'KEYNAME_EXT', 'KEYNAME_DEAD', 'DESCRIPTIONS', 'LANGUAGENAMES', 'ENDKBD'];

function section(name) {
  const start = lines.findIndex((l) => l.split(/\s/)[0] === name);
  if (start < 0) return [];
  const body = [];
  for (let i = start + 1; i < lines.length; i++) {
    const head = lines[i].split(/\s/)[0];
    if (SECTIONS.includes(head)) break;
    const clean = lines[i].replace(/\/\/.*$/, '').replace(/^;.*$/, '').trim();
    if (clean) body.push(clean);
  }
  return body;
}

for (const unsupported of ['DEADKEY', 'LIGATURE', 'KEYNAME_DEAD']) {
  if (section(unsupported).length) throw new Error(`${unsupported} is not supported`);
}

const shiftStates = section('SHIFTSTATE').map((l) => parseInt(l, 10));
const altGr = lines.some((l) => l.trim() === 'ALTGR');

function vkName(v) {
  return /^[0-9A-Z]$/.test(v) ? `'${v}'` : `VK_${v}`;
}

function wch(cell) {
  if (cell === '-1') return 'WCH_NONE';
  if (cell.endsWith('@')) throw new Error(`dead key ${cell} is not supported`);
  if (cell.length === 1) {
    if (cell === "'" || cell === '\\') return `L'\\${cell}'`;
    return `L'${cell}'`;
  }
  if (/^[0-9a-fA-F]{4}$/.test(cell)) return `0x${cell.toLowerCase()}`;
  throw new Error(`cannot parse character cell "${cell}"`);
}

function attr(cap) {
  if (cap === '0') return '0';
  if (cap === '1') return 'CAPLOK';
  throw new Error(`Cap value "${cap}" is not supported`);
}

// --- LAYOUT -------------------------------------------------------------
const rows = [];
for (const l of section('LAYOUT')) {
  const t = l.split(/\s+/);
  const [sc, vk, cap, ...cells] = t;
  if (cells.length !== shiftStates.length) throw new Error(`bad LAYOUT row: ${l}`);
  if (vk === 'DECIMAL') {
    // Numpad decimal: only the first two columns are meaningful.
    rows.push({ sc, vk, cap, cells: cells.slice(0, 2) });
    continue;
  }
  let width = cells.length;
  while (width > 2 && cells[width - 1] === '-1') width--;
  rows.push({ sc, vk, cap, cells: cells.slice(0, width) });
}

const fixed = [
  { vk: 'TAB', cap: '0', lit: ["'\\t'", "'\\t'"] },
  { vk: 'ADD', cap: '0', lit: ["'+'", "'+'"] },
  { vk: 'DIVIDE', cap: '0', lit: ["'/'", "'/'"] },
  { vk: 'MULTIPLY', cap: '0', lit: ["'*'", "'*'"] },
  { vk: 'SUBTRACT', cap: '0', lit: ["'-'", "'-'"] },
  { vk: 'BACK', cap: '0', lit: ["'\\b'", "'\\b'", '0x007f'] },
  { vk: 'ESCAPE', cap: '0', lit: ['0x001b', '0x001b', '0x001b'] },
  { vk: 'RETURN', cap: '0', lit: ["'\\r'", "'\\r'", "'\\n'"] },
  { vk: 'CANCEL', cap: '0', lit: ['0x0003', '0x0003', '0x0003'] },
];

const tables = new Map(); // width -> lines
function add(width, line) {
  if (!tables.has(width)) tables.set(width, []);
  tables.get(width).push(line);
}
for (const r of rows) {
  add(r.cells.length, `    {${vkName(r.vk)}, ${attr(r.cap)}, {${r.cells.map(wch).join(', ')}}},`);
}
for (const f of fixed) {
  add(f.lit.length, `    {VK_${f.vk}, ${attr(f.cap)}, {${f.lit.join(', ')}}},`);
}
for (let d = 0; d <= 9; d++) add(1, `    {VK_NUMPAD${d}, 0, {'${d}'}},`);

const widths = [...tables.keys()].sort((a, b) => a - b);
// Wide tables first, then the two-column one, the numpad last, so VkKeyScan
// prefers keys from the main block.
const order = [...widths.filter((w) => w >= 3), ...widths.filter((w) => w === 2), ...widths.filter((w) => w === 1)];

// --- modifiers ------------------------------------------------------------
const maxBits = Math.max(...shiftStates);
const modNumbers = [];
for (let bits = 0; bits <= maxBits; bits++) {
  const idx = shiftStates.indexOf(bits);
  modNumbers.push(idx < 0 ? 'SHFT_INVALID' : String(idx));
}

// --- key names ------------------------------------------------------------
function names(sec) {
  return section(sec).map((l) => {
    const m = l.match(/^([0-9a-fA-F]+)\s+(.*)$/);
    const name = m[2].replace(/^"(.*)"$/, '$1');
    return `    {0x${m[1].toLowerCase()}, L"${name.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"},`;
  });
}

